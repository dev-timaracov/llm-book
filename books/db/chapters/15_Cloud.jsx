function AuroraQuorum() {
  const [down, setDown] = useState([false, false, false, false, false, false]);
  const alive = down.filter((d) => !d).length;
  const toggle = (i) => setDown(down.map((d, j) => (j === i ? !d : d)));
  const az = [0, 1, 2].map((a) => [2 * a, 2 * a + 1]);
  return (
    <Widget title="Кворум Aurora: 6 копий в 3 зонах доступности">
      <div style={{ display: 'flex', gap: 12, flexWrap: 'wrap' }}>
        {az.map((pair, a) => (
          <div key={a} style={{ border: '1px dashed var(--border)', borderRadius: 10, padding: 8 }}>
            <div className="small muted">зона {String.fromCharCode(65 + a)}</div>
            <div style={{ display: 'flex', gap: 6, marginTop: 4 }}>
              {pair.map((i) => <button key={i} className="btn" onClick={() => toggle(i)} style={{ background: down[i] ? 'var(--red-soft)' : 'var(--green-soft)' }}>{down[i] ? '✗' : '●'} копия {i + 1}</button>)}
            </div>
            <button className="btn small" style={{ marginTop: 6 }} onClick={() => setDown(down.map((d, j) => (pair.includes(j) ? true : d)))}>отключить зону</button>
          </div>
        ))}
      </div>
      <div className="stats">
        <Stat k="живых копий" v={alive} />
        <Stat k="запись (нужно 4/6)" v={alive >= 4 ? '✓ работает' : '✗ невозможна'} />
        <Stat k="чтение/восстановление (нужно 3/6)" v={alive >= 3 ? '✓ работает' : '✗ данные недоступны'} />
      </div>
      <button className="btn small" onClick={() => setDown(down.map(() => false))}>починить всё</button>
      <p className="small muted">Цель Aurora: пережить потерю целой зоны и ещё одного узла (AZ+1) без потери данных и потерю зоны — без остановки записи. V<sub>w</sub> = 4 и V<sub>r</sub> = 3 при V = 6: V<sub>r</sub> + V<sub>w</sub> &gt; V (чтение пересекается с записью) и 2V<sub>w</sub> &gt; V (две записи не могут пройти независимо).</p>
    </Widget>
  );
}

function ElasticityWidget() {
  const [work, setWork] = useState(64);
  const [serial, setSerial] = useState(0.05);
  const [price, setPrice] = useState(2);
  const ns = [1, 2, 4, 8, 16, 32, 64, 128];
  const time = (n) => work * (serial + (1 - serial) / n);
  const pts = ns.map((n) => ({ n, t: time(n), cost: time(n) * n * price }));
  return (
    <Widget title="Эластичность: больше узлов — быстрее, а стоит ли дороже?">
      <div className="controls">
        <Slider label="работа запроса, узло-часов" value={work} min={1} max={256} onChange={setWork} />
        <Slider label="непараллелизуемая доля (Амдал)" value={serial} min={0} max={0.5} step={0.01} onChange={setSerial} />
        <Slider label="цена узла, $/час" value={price} min={0.5} max={10} step={0.5} onChange={setPrice} />
      </div>
      <table className="small">
        <thead><tr><th>Узлов</th><th>Время</th><th>Стоимость</th></tr></thead>
        <tbody>{pts.map((p) => <tr key={p.n}><td>{p.n}</td><td>{p.t >= 1 ? fmt(p.t, 1) + ' ч' : fmt(p.t * 60, 0) + ' мин'}</td><td>${fmt(p.cost, 0)}</td></tr>)}</tbody>
      </table>
      <LineChart height={180} series={[{ data: pts.map((p) => [Math.log2(p.n), p.cost]), color: 'var(--c2)', label: 'стоимость, $', points: true }]} xLabel="log₂(узлов)" />
      <p className="small muted">Если работа идеально делится (доля 0), 64 узла на 1 час стоят столько же, сколько 1 узел на 64 часа: оплата посекундная, а результат в 64 раза быстрее. Это главный экономический аргумент разделения хранения и вычислений: вычислительный кластер можно поднять на время запроса и выключить. Непараллелизуемая часть делает «широкие» конфигурации дороже — оптимум находится где-то посередине <Cite id="leis2021cloud" />.</p>
    </Widget>
  );
}

